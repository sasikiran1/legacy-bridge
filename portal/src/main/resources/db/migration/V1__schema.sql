CREATE TABLE portal_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL UNIQUE,
    display_name  VARCHAR(128) NOT NULL,
    role          VARCHAR(16)  NOT NULL CHECK (role IN ('CLERK', 'SUPERVISOR')),
    password_hash VARCHAR(256)
);

CREATE TABLE member (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_number VARCHAR(16)  NOT NULL UNIQUE,
    first_name    VARCHAR(64)  NOT NULL,
    last_name     VARCHAR(64)  NOT NULL,
    date_of_birth DATE         NOT NULL,
    ssn           VARCHAR(11)  NOT NULL,
    email         VARCHAR(128) NOT NULL,
    phone         VARCHAR(32)  NOT NULL,
    street        VARCHAR(128) NOT NULL,
    city          VARCHAR(64)  NOT NULL,
    state         VARCHAR(2)   NOT NULL,
    postal_code   VARCHAR(10)  NOT NULL,
    version       INTEGER      NOT NULL DEFAULT 0,
    updated_at    TIMESTAMPTZ,
    updated_by    VARCHAR(64)
);
CREATE INDEX member_last_name_idx ON member (lower(last_name));

CREATE TABLE policy (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_number   VARCHAR(20)   NOT NULL UNIQUE,
    member_id       BIGINT        NOT NULL REFERENCES member (id),
    product         VARCHAR(64)   NOT NULL,
    status          VARCHAR(16)   NOT NULL CHECK (status IN ('ACTIVE', 'LAPSED', 'CANCELLED')),
    effective_date  DATE          NOT NULL,
    monthly_premium NUMERIC(10, 2) NOT NULL
);
CREATE INDEX policy_member_idx ON policy (member_id);

CREATE TABLE claim (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_number              VARCHAR(20)    NOT NULL UNIQUE,
    policy_id                 BIGINT         NOT NULL REFERENCES policy (id),
    service_date              DATE           NOT NULL,
    provider_name             VARCHAR(128)   NOT NULL,
    amount                    NUMERIC(10, 2) NOT NULL,
    status                    VARCHAR(16)    NOT NULL
        CHECK (status IN ('RECEIVED', 'IN_REVIEW', 'APPROVED', 'DENIED', 'PAID')),
    reconsideration_requested BOOLEAN        NOT NULL DEFAULT FALSE,
    updated_at                TIMESTAMPTZ,
    updated_by                VARCHAR(64)
);
CREATE INDEX claim_policy_idx ON claim (policy_id);

CREATE TABLE reimbursement (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference    VARCHAR(16)    NOT NULL UNIQUE,
    member_id    BIGINT         NOT NULL REFERENCES member (id),
    claim_id     BIGINT         REFERENCES claim (id),
    amount       NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
    payee_name   VARCHAR(128)   NOT NULL,
    bank_routing VARCHAR(9)     NOT NULL,
    bank_account VARCHAR(17)    NOT NULL,
    status       VARCHAR(16)    NOT NULL DEFAULT 'SUBMITTED',
    submitted_at TIMESTAMPTZ    NOT NULL,
    submitted_by VARCHAR(64)    NOT NULL
);

CREATE TABLE member_note (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  BIGINT      NOT NULL REFERENCES member (id),
    author     VARCHAR(64) NOT NULL,
    body       TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    injected   BOOLEAN     NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ,
    deleted_by VARCHAR(64)
);
CREATE INDEX member_note_member_idx ON member_note (member_id);
